"""Write results to disk as a timestamped bundle, and build a 7-day
content calendar CSV for scheduling."""
from __future__ import annotations

import csv
import io
import zipfile
from datetime import datetime, timedelta
from pathlib import Path

from . import limits

OUTPUT_ROOT = Path(__file__).resolve().parent.parent / "output"


def _platform_markdown(platform: str, result: dict) -> str:
    lines = [f"# {limits.DISPLAY_NAME[platform]}", ""]
    if result.get("title"):
        lines += [f"**Title/Subject:** {result['title']}", ""]
    lines += ["## Hook options", ""]
    for i, hook in enumerate(result["hooks"], 1):
        score = result.get("hook_scores", [{}] * 3)[i - 1].get("score", "-")
        lines.append(f"{i}. ({score}/100) {hook}")
    lines += ["", "## Post", "", result["body"], ""]
    if result.get("hashtags"):
        lines += ["## Hashtags", " ".join(result["hashtags"]), ""]
    lines += [f"_Best time to post: {limits.BEST_TIMES.get(platform, '-')}_", f"_Generated by: {result.get('engine', '?')}_"]
    return "\n".join(lines)


def write_bundle(results: dict, source_name: str = "source") -> Path:
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    run_dir = OUTPUT_ROOT / f"run_{ts}"
    run_dir.mkdir(parents=True, exist_ok=True)

    for platform, result in results.items():
        if platform == "_meta":
            continue
        (run_dir / f"{platform}.md").write_text(_platform_markdown(platform, result), encoding="utf-8")

    calendar_csv = build_calendar_csv(results)
    (run_dir / "content_calendar.csv").write_text(calendar_csv, encoding="utf-8")

    return run_dir


def build_calendar_csv(results: dict) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["date", "platform", "best_time", "hook", "post_preview", "status"])

    today = datetime.now().date()
    platforms = [p for p in results if p != "_meta"]
    for i, platform in enumerate(platforms):
        result = results[platform]
        post_date = today + timedelta(days=i % 7)
        preview = result["body"].replace("\n", " ")[:120]
        writer.writerow([
            post_date.isoformat(),
            limits.DISPLAY_NAME.get(platform, platform),
            limits.BEST_TIMES.get(platform, ""),
            result["hooks"][0] if result.get("hooks") else "",
            preview,
            "draft",
        ])
    return buf.getvalue()


def build_zip(results: dict) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for platform, result in results.items():
            if platform == "_meta":
                continue
            zf.writestr(f"{platform}.md", _platform_markdown(platform, result))
        zf.writestr("content_calendar.csv", build_calendar_csv(results))
    return buf.getvalue()
